import * as crypto from 'crypto'
import * as fs from 'fs'
import * as path from 'path'
import * as zlib from 'zlib'

export const PROCEDURAL_ASSET_KINDS = [
	'globe',
	'terrain',
	'leaf',
	'tree-canopy',
	'river-ribbon',
	'route-arc',
	'abstract-hero',
	'growth-arrow',
	'biome-scene',
] as const

export type ProceduralAssetKind = typeof PROCEDURAL_ASSET_KINDS[number]

export interface ProceduralAssetResult {
	handle: string
	id: string
	kind: ProceduralAssetKind
	source: 'generated'
	src: string
	preview: string
	altText: string
	tags: string[]
	usage: string
	license: string
	metadata: Record<string, unknown>
}

interface Mesh {
	positions: number[]
	normals: number[]
	indices: number[]
}

interface MeshPart extends Mesh {
	offset?: [number, number, number]
	scale?: [number, number, number]
}

const BRAND = 'betterpptx-mcp'
const LICENSE = 'Generated by betterpptx-mcp procedural generator for the requesting workspace.'

function ensureDir(dir: string): void {
	fs.mkdirSync(dir, { recursive: true })
}

function safeId(value: string): string {
	return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'asset'
}

function hash(value: string): string {
	return crypto.createHash('sha256').update(value).digest('hex').slice(0, 12)
}

function rng(seed: string): () => number {
	let state = crypto.createHash('sha256').update(seed).digest().readUInt32LE(0) || 1
	return () => {
		state ^= state << 13
		state ^= state >>> 17
		state ^= state << 5
		return ((state >>> 0) % 100000) / 100000
	}
}

function colorFor(kind: ProceduralAssetKind, theme = ''): [number, number, number, number] {
	const rain = /rain|forest|earth|biome|nature/i.test(theme)
	const colors: Record<ProceduralAssetKind, [number, number, number, number]> = {
		globe: rain ? [0.05, 0.48, 0.36, 1] : [0.08, 0.44, 0.86, 1],
		terrain: [0.12, 0.44, 0.18, 1],
		leaf: [0.1, 0.64, 0.28, 1],
		'tree-canopy': [0.05, 0.48, 0.2, 1],
		'river-ribbon': [0.05, 0.62, 0.9, 1],
		'route-arc': [0.96, 0.7, 0.16, 1],
		'abstract-hero': [0.15, 0.72, 0.9, 1],
		'growth-arrow': [0.18, 0.86, 0.54, 1],
		'biome-scene': [0.08, 0.52, 0.24, 1],
	}
	return colors[kind]
}

function normalize(x: number, y: number, z: number): [number, number, number] {
	const len = Math.sqrt(x * x + y * y + z * z) || 1
	return [x / len, y / len, z / len]
}

function sphereMesh(lat = 24, lon = 40, radius = 1): Mesh {
	const positions: number[] = []
	const normals: number[] = []
	const indices: number[] = []
	for (let y = 0; y <= lat; y++) {
		const v = y / lat
		const theta = v * Math.PI
		for (let x = 0; x <= lon; x++) {
			const u = x / lon
			const phi = u * Math.PI * 2
			const nx = Math.sin(theta) * Math.cos(phi)
			const ny = Math.cos(theta)
			const nz = Math.sin(theta) * Math.sin(phi)
			positions.push(nx * radius, ny * radius, nz * radius)
			normals.push(nx, ny, nz)
		}
	}
	for (let y = 0; y < lat; y++) {
		for (let x = 0; x < lon; x++) {
			const a = y * (lon + 1) + x
			const b = a + lon + 1
			indices.push(a, b, a + 1, b, b + 1, a + 1)
		}
	}
	return { positions, normals, indices }
}

function terrainMesh(seed: string, size = 20): Mesh {
	const rand = rng(seed)
	const positions: number[] = []
	const normals: number[] = []
	const indices: number[] = []
	for (let z = 0; z <= size; z++) {
		for (let x = 0; x <= size; x++) {
			const px = x / size * 2 - 1
			const pz = z / size * 2 - 1
			const hill = Math.sin(px * Math.PI * 2) * 0.09 + Math.cos(pz * Math.PI * 2) * 0.08 + (rand() - 0.5) * 0.04
			positions.push(px, hill, pz)
			normals.push(...normalize(-0.12 * Math.cos(px * 4), 1, -0.12 * Math.sin(pz * 4)))
		}
	}
	for (let z = 0; z < size; z++) {
		for (let x = 0; x < size; x++) {
			const a = z * (size + 1) + x
			const b = a + size + 1
			indices.push(a, b, a + 1, b, b + 1, a + 1)
		}
	}
	return { positions, normals, indices }
}

function leafMesh(): Mesh {
	const positions: number[] = []
	const normals: number[] = []
	const indices: number[] = []
	const rows = 16
	for (let i = 0; i <= rows; i++) {
		const t = i / rows
		const y = (t - 0.5) * 2
		const half = Math.sin(t * Math.PI) * 0.5
		const curve = Math.sin((t - 0.2) * Math.PI) * 0.18
		positions.push(-half, curve, y, half, curve, y)
		normals.push(0, 1, 0, 0, 1, 0)
	}
	for (let i = 0; i < rows; i++) {
		const a = i * 2
		indices.push(a, a + 2, a + 1, a + 1, a + 2, a + 3)
	}
	return { positions, normals, indices }
}

function ribbonMesh(seed: string, turns = 28): Mesh {
	const rand = rng(seed)
	const positions: number[] = []
	const normals: number[] = []
	const indices: number[] = []
	for (let i = 0; i <= turns; i++) {
		const t = i / turns
		const angle = t * Math.PI * 2.2
		const x = (t - 0.5) * 2.2
		const y = Math.sin(angle) * 0.32
		const z = Math.cos(angle) * 0.24 + (rand() - 0.5) * 0.03
		const width = 0.08 + Math.sin(t * Math.PI) * 0.06
		positions.push(x, y + width, z, x, y - width, z)
		normals.push(0, 0.8, 0.6, 0, 0.8, 0.6)
	}
	for (let i = 0; i < turns; i++) {
		const a = i * 2
		indices.push(a, a + 2, a + 1, a + 1, a + 2, a + 3)
	}
	return { positions, normals, indices }
}

function arrowMesh(): Mesh {
	const positions = [
		-1.0, -0.12, -0.08, 0.35, -0.12, -0.08, 0.35, -0.32, -0.08, 1.0, 0, -0.08, 0.35, 0.32, -0.08, 0.35, 0.12, -0.08, -1.0, 0.12, -0.08,
		-1.0, -0.12, 0.08, 0.35, -0.12, 0.08, 0.35, -0.32, 0.08, 1.0, 0, 0.08, 0.35, 0.32, 0.08, 0.35, 0.12, 0.08, -1.0, 0.12, 0.08,
	]
	const normals: number[] = []
	for (let i = 0; i < positions.length / 3; i++) normals.push(0, 0, i < 7 ? -1 : 1)
	const front = [0, 1, 5, 0, 5, 6, 1, 2, 3, 1, 3, 4, 1, 4, 5]
	const back = front.map(i => i + 7).reverse()
	const sides: number[] = []
	for (let i = 0; i < 7; i++) {
		const j = (i + 1) % 7
		sides.push(i, j, i + 7, j, j + 7, i + 7)
	}
	return { positions, normals, indices: [...front, ...back, ...sides] }
}

function mergeMeshes(parts: MeshPart[]): Mesh {
	const positions: number[] = []
	const normals: number[] = []
	const indices: number[] = []
	let vertexOffset = 0
	for (const part of parts) {
		const scale = part.scale || [1, 1, 1]
		const offset = part.offset || [0, 0, 0]
		for (let i = 0; i < part.positions.length; i += 3) {
			positions.push(part.positions[i] * scale[0] + offset[0], part.positions[i + 1] * scale[1] + offset[1], part.positions[i + 2] * scale[2] + offset[2])
		}
		normals.push(...part.normals)
		indices.push(...part.indices.map(index => index + vertexOffset))
		vertexOffset += part.positions.length / 3
	}
	return { positions, normals, indices }
}

function meshFor(kind: ProceduralAssetKind, seed: string): Mesh {
	if (kind === 'globe') return sphereMesh(28, 44, 1)
	if (kind === 'terrain') return terrainMesh(seed, 24)
	if (kind === 'leaf') return leafMesh()
	if (kind === 'tree-canopy') {
		const rand = rng(seed)
		return mergeMeshes(Array.from({ length: 7 }, (_, i) => ({
			...sphereMesh(12, 16, 0.42 + rand() * 0.12),
			offset: [(i % 3 - 1) * 0.42, 0.18 + Math.floor(i / 3) * 0.26, (rand() - 0.5) * 0.5],
			scale: [1.15, 0.72, 1],
		})))
	}
	if (kind === 'river-ribbon' || kind === 'route-arc' || kind === 'abstract-hero') return ribbonMesh(seed, kind === 'abstract-hero' ? 42 : 30)
	if (kind === 'growth-arrow') return arrowMesh()
	if (kind === 'biome-scene') {
		return mergeMeshes([
			{ ...terrainMesh(seed, 18), scale: [1.4, 0.55, 1.1], offset: [0, -0.5, 0] },
			{ ...sphereMesh(12, 16, 1), scale: [0.28, 0.22, 0.28], offset: [-0.48, 0.08, -0.32] },
			{ ...sphereMesh(12, 16, 1), scale: [0.34, 0.25, 0.34], offset: [0.08, 0.14, 0.1] },
			{ ...sphereMesh(12, 16, 1), scale: [0.25, 0.2, 0.25], offset: [0.58, 0.06, -0.18] },
			{ ...ribbonMesh(`${seed}:river`, 20), scale: [0.68, 0.22, 0.42], offset: [0, -0.22, 0.1] },
		])
	}
	return sphereMesh()
}

function writeFloat32(buffer: Buffer, value: number, offset: number): void {
	buffer.writeFloatLE(value, offset)
}

function minMax(values: number[]): { min: [number, number, number]; max: [number, number, number] } {
	const min: [number, number, number] = [Infinity, Infinity, Infinity]
	const max: [number, number, number] = [-Infinity, -Infinity, -Infinity]
	for (let i = 0; i < values.length; i += 3) {
		for (let axis = 0; axis < 3; axis++) {
			min[axis] = Math.min(min[axis], values[i + axis])
			max[axis] = Math.max(max[axis], values[i + axis])
		}
	}
	return { min, max }
}

function pad4(buffer: Buffer, pad = 0): Buffer {
	const extra = (4 - buffer.length % 4) % 4
	return extra ? Buffer.concat([buffer, Buffer.alloc(extra, pad)]) : buffer
}

function glbBuffer(mesh: Mesh, color: [number, number, number, number], name: string): Buffer {
	const positionBytes = Buffer.alloc(mesh.positions.length * 4)
	mesh.positions.forEach((value, index) => writeFloat32(positionBytes, value, index * 4))
	const normalBytes = Buffer.alloc(mesh.normals.length * 4)
	mesh.normals.forEach((value, index) => writeFloat32(normalBytes, value, index * 4))
	const indexComponentType = mesh.positions.length / 3 > 65535 ? 5125 : 5123
	const indexBytes = Buffer.alloc(mesh.indices.length * (indexComponentType === 5125 ? 4 : 2))
	mesh.indices.forEach((value, index) => {
		if (indexComponentType === 5125) indexBytes.writeUInt32LE(value, index * 4)
		else indexBytes.writeUInt16LE(value, index * 2)
	})
	const positionOffset = 0
	const normalOffset = pad4(positionBytes).length
	const indexOffset = normalOffset + pad4(normalBytes).length
	const bin = pad4(Buffer.concat([pad4(positionBytes), pad4(normalBytes), pad4(indexBytes)]))
	const extents = minMax(mesh.positions)
	const json = {
		asset: { version: '2.0', generator: `${BRAND} procedural asset generator` },
		scene: 0,
		scenes: [{ nodes: [0] }],
		nodes: [{ mesh: 0, name }],
		meshes: [{ primitives: [{ attributes: { POSITION: 0, NORMAL: 1 }, indices: 2, material: 0 }] }],
		materials: [{
			name: `${BRAND} procedural material`,
			pbrMetallicRoughness: { baseColorFactor: color, metallicFactor: 0.18, roughnessFactor: 0.38 },
			doubleSided: true,
		}],
		buffers: [{ byteLength: bin.length }],
		bufferViews: [
			{ buffer: 0, byteOffset: positionOffset, byteLength: positionBytes.length, target: 34962 },
			{ buffer: 0, byteOffset: normalOffset, byteLength: normalBytes.length, target: 34962 },
			{ buffer: 0, byteOffset: indexOffset, byteLength: indexBytes.length, target: 34963 },
		],
		accessors: [
			{ bufferView: 0, componentType: 5126, count: mesh.positions.length / 3, type: 'VEC3', min: extents.min, max: extents.max },
			{ bufferView: 1, componentType: 5126, count: mesh.normals.length / 3, type: 'VEC3' },
			{ bufferView: 2, componentType: indexComponentType, count: mesh.indices.length, type: 'SCALAR' },
		],
		extras: { brand: BRAND, license: LICENSE },
	}
	const jsonChunk = pad4(Buffer.from(JSON.stringify(json)), 0x20)
	const totalLength = 12 + 8 + jsonChunk.length + 8 + bin.length
	const header = Buffer.alloc(12)
	header.writeUInt32LE(0x46546c67, 0)
	header.writeUInt32LE(2, 4)
	header.writeUInt32LE(totalLength, 8)
	const jsonHeader = Buffer.alloc(8)
	jsonHeader.writeUInt32LE(jsonChunk.length, 0)
	jsonHeader.writeUInt32LE(0x4e4f534a, 4)
	const binHeader = Buffer.alloc(8)
	binHeader.writeUInt32LE(bin.length, 0)
	binHeader.writeUInt32LE(0x004e4942, 4)
	return Buffer.concat([header, jsonHeader, jsonChunk, binHeader, bin])
}

function crc32(buffer: Buffer): number {
	let crc = 0xffffffff
	for (const byte of buffer) {
		crc ^= byte
		for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1))
	}
	return (crc ^ 0xffffffff) >>> 0
}

function pngChunk(type: string, data: Buffer): Buffer {
	const typeBuffer = Buffer.from(type)
	const out = Buffer.alloc(12 + data.length)
	out.writeUInt32BE(data.length, 0)
	typeBuffer.copy(out, 4)
	data.copy(out, 8)
	out.writeUInt32BE(crc32(Buffer.concat([typeBuffer, data])), 8 + data.length)
	return out
}

function writePoster(filePath: string, kind: ProceduralAssetKind, color: [number, number, number, number]): void {
	const width = 960
	const height = 540
	const raw = Buffer.alloc((width * 4 + 1) * height)
	const [r, g, b] = color.map(value => Math.round(value * 255))
	for (let y = 0; y < height; y++) {
		const row = y * (width * 4 + 1)
		raw[row] = 0
		for (let x = 0; x < width; x++) {
			const i = row + 1 + x * 4
			const dx = x / width
			const dy = y / height
			const glow = Math.max(0, 1 - Math.hypot(dx - 0.64, dy - 0.46) * 1.65)
			raw[i] = Math.min(255, Math.round(8 + r * glow + 22 * dx))
			raw[i + 1] = Math.min(255, Math.round(16 + g * glow + 26 * (1 - dy)))
			raw[i + 2] = Math.min(255, Math.round(24 + b * glow + 36 * dy))
			raw[i + 3] = 255
			if (kind === 'globe') {
				const d = Math.hypot(dx - 0.6, dy - 0.5)
				if (d > 0.18 && d < 0.28) {
					raw[i] = Math.min(255, raw[i] + 18)
					raw[i + 1] = Math.min(255, raw[i + 1] + 72)
					raw[i + 2] = Math.min(255, raw[i + 2] + 58)
				}
			}
			if (kind.includes('river') || kind.includes('route')) {
				const wave = Math.abs(dy - (0.54 + Math.sin(dx * Math.PI * 4) * 0.08))
				if (wave < 0.025) {
					raw[i] = 38
					raw[i + 1] = 212
					raw[i + 2] = 238
				}
			}
			if (kind.includes('leaf') || kind.includes('canopy') || kind.includes('biome')) {
				const canopy = Math.sin(dx * Math.PI * 8) * 0.04 + 0.45
				if (dy > canopy && dy < canopy + 0.16) {
					raw[i] = 22
					raw[i + 1] = Math.min(255, raw[i + 1] + 90)
					raw[i + 2] = 70
				}
			}
		}
	}
	const ihdr = Buffer.alloc(13)
	ihdr.writeUInt32BE(width, 0)
	ihdr.writeUInt32BE(height, 4)
	ihdr[8] = 8
	ihdr[9] = 6
	const png = Buffer.concat([
		Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
		pngChunk('IHDR', ihdr),
		pngChunk('IDAT', zlib.deflateSync(raw)),
		pngChunk('IEND', Buffer.alloc(0)),
	])
	fs.writeFileSync(filePath, png)
}

function normalizeKind(kind: unknown): ProceduralAssetKind {
	const normalized = safeId(String(kind || 'abstract-hero'))
	const found = PROCEDURAL_ASSET_KINDS.find(item => safeId(item) === normalized)
	return found || 'abstract-hero'
}

function parseHandle(handle: string): { kind: ProceduralAssetKind; seed: string; theme: string; style: string } | null {
	if (!handle.startsWith('procedural3d://')) return null
	const raw = handle.slice('procedural3d://'.length)
	const [kindPart, query = ''] = raw.split('?')
	const params = new URLSearchParams(query)
	return {
		kind: normalizeKind(kindPart),
		seed: params.get('seed') || kindPart || 'default',
		theme: params.get('theme') || '',
		style: params.get('style') || '',
	}
}

export function isProceduralAssetHandle(value: unknown): value is string {
	return typeof value === 'string' && value.startsWith('procedural3d://')
}

export function proceduralAssetTemplates(repoRoot: string): ProceduralAssetResult[] {
	const preview = path.resolve(repoRoot, 'demos/ultimate-showcase/assets/model-fallback.png')
	return PROCEDURAL_ASSET_KINDS.map(kind => ({
		handle: `procedural3d://${kind}`,
		id: `template-${kind}`,
		kind,
		source: 'generated',
		src: repoRoot,
		preview,
		altText: `${BRAND} procedural ${kind} 3D asset template`,
		tags: ['generated', 'procedural', '3d', 'glb', kind, 'cinematic', 'offline'],
		usage: `Generate a deterministic native GLB ${kind} model with poster fallback inside an MCP job.`,
		license: LICENSE,
		metadata: { template: true, accepts: ['seed', 'theme', 'style'] },
	}))
}

export function generateProceduralAsset(repoRoot: string, outputDir: string, request: { kind?: unknown; seed?: unknown; theme?: unknown; style?: unknown; id?: unknown } = {}): ProceduralAssetResult {
	const kind = normalizeKind(request.kind)
	const seed = String(request.seed || `${kind}:default`)
	const theme = String(request.theme || '')
	const style = String(request.style || 'cinematic')
	const id = safeId(String(request.id || `${kind}-${hash(`${kind}:${seed}:${theme}:${style}`)}`))
	const dir = path.join(outputDir, 'procedural-assets')
	ensureDir(dir)
	const glbPath = path.join(dir, `${id}.glb`)
	const posterPath = path.join(dir, `${id}.png`)
	const metadataPath = path.join(dir, `${id}.json`)
	const color = colorFor(kind, theme)
	if (!fs.existsSync(glbPath)) fs.writeFileSync(glbPath, glbBuffer(meshFor(kind, `${seed}:${theme}:${style}`), color, `${BRAND} ${kind}`))
	if (!fs.existsSync(posterPath)) writePoster(posterPath, kind, color)
	const result: ProceduralAssetResult = {
		handle: `procedural3d://${kind}?seed=${encodeURIComponent(seed)}&theme=${encodeURIComponent(theme)}&style=${encodeURIComponent(style)}`,
		id,
		kind,
		source: 'generated',
		src: glbPath,
		preview: posterPath,
		altText: `${BRAND} generated ${kind} 3D model`,
		tags: ['generated', 'procedural', '3d', 'glb', kind, theme, style].filter(Boolean),
		usage: `Native GLB ${kind} model generated deterministically for a presentation job.`,
		license: LICENSE,
		metadata: { brand: BRAND, kind, seed, theme, style, source: 'procedural-generator', repoRoot: path.basename(repoRoot) },
	}
	fs.writeFileSync(metadataPath, JSON.stringify(result, null, 2))
	return result
}

export function materializeProceduralAssetHandle(handle: string, repoRoot: string, outputDir: string): ProceduralAssetResult | null {
	const parsed = parseHandle(handle)
	if (!parsed) return null
	return generateProceduralAsset(repoRoot, outputDir, parsed)
}
