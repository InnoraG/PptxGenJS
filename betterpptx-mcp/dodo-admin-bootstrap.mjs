import * as fs from 'node:fs'
import * as path from 'node:path'
import * as crypto from 'node:crypto'
import { spawn } from 'node:child_process'

const __dirname = path.dirname(new URL(import.meta.url).pathname)
const here = process.platform === 'win32' && __dirname.startsWith('/') ? __dirname.slice(1) : __dirname
const privateDir = path.join(here, '.betterpptx-mcp-runtime')
const envFile = path.join(privateDir, 'dodo-local.env')
const statusFile = path.join(privateDir, 'dodo-bootstrap-status.json')
const dodoBase = 'https://test.dodopayments.com'
const verifyPort = Number(process.env.BETTERPPTX_VERIFY_PORT || 3346)
const verifyMcpUrl = `http://127.0.0.1:${verifyPort}/mcp`

function readEnvFile(file) {
	if (!fs.existsSync(file)) return {}
	const env = {}
	for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
		const m = line.match(/^\s*([^#=\s]+)\s*=\s*(.*?)\s*$/)
		if (!m) continue
		let value = m[2].trim()
		if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
			value = value.slice(1, -1)
		}
		env[m[1]] = value.replace(/\\n/g, '\n').replace(/\\"/g, '"')
	}
	return env
}

function escapeEnvValue(value) {
	return `"${String(value ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function writeEnvFile(file, values) {
	fs.mkdirSync(path.dirname(file), { recursive: true })
	const lines = [
		'# BetterPPTX local Dodo test configuration',
		'# PRIVATE. Do not commit or paste these values in chat.',
		'# Generated by betterpptx-mcp/setup-dodo-local.ps1 and dodo-admin-bootstrap.mjs.',
		'',
	]
	for (const key of Object.keys(values).sort()) {
		const value = values[key]
		if (value === undefined || value === null || String(value).trim() === '') continue
		lines.push(`${key}=${escapeEnvValue(value)}`)
	}
	fs.writeFileSync(file, `${lines.join('\n')}\n`, 'utf8')
}

function generateLicenseKey() {
	const groups = [4, 4, 4, 4].map(n => crypto.randomBytes(n).toString('hex').slice(0, n).toUpperCase())
	return `BPPTX-TEST-${groups.join('-')}`
}

async function dodo(pathname, { method = 'GET', body, token, allowConflict = false } = {}) {
	const headers = { Accept: 'application/json' }
	if (token) headers.Authorization = `Bearer ${token}`
	if (body !== undefined) headers['Content-Type'] = 'application/json'
	const response = await fetch(`${dodoBase}${pathname}`, {
		method,
		headers,
		body: body === undefined ? undefined : JSON.stringify(body),
	})
	const raw = await response.text()
	let data = null
	try { data = raw ? JSON.parse(raw) : null } catch { data = { raw } }
	if (!response.ok && !(allowConflict && response.status === 409)) {
		const msg = data?.message || data?.error || data?.raw || response.statusText
		throw new Error(`Dodo ${method} ${pathname} failed with HTTP ${response.status}: ${msg}`)
	}
	return { status: response.status, data }
}

async function validateLicensePublic(licenseKey) {
	const response = await fetch(`${dodoBase}/licenses/validate`, {
		method: 'POST',
		headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
		body: JSON.stringify({ license_key: licenseKey }),
	})
	const raw = await response.text()
	let data = null
	try { data = raw ? JSON.parse(raw) : null } catch { data = { raw } }
	if (!response.ok) {
		const msg = data?.message || data?.error || data?.raw || response.statusText
		throw new Error(`Dodo public license validation failed with HTTP ${response.status}: ${msg}`)
	}
	return data || {}
}

async function waitHttp(url, timeoutMs = 30000) {
	const deadline = Date.now() + timeoutMs
	while (Date.now() < deadline) {
		try {
			const res = await fetch(url)
			if (res.ok || res.status < 500) return true
		} catch {}
		await new Promise(resolve => setTimeout(resolve, 500))
	}
	return false
}

function runNode(args, { env, quiet = false } = {}) {
	return new Promise((resolve, reject) => {
		const child = spawn(process.execPath, args, {
			cwd: here,
			env,
			stdio: quiet ? ['ignore', 'pipe', 'pipe'] : 'inherit',
			windowsHide: true,
		})
		let stdout = ''
		let stderr = ''
		if (quiet) {
			child.stdout.on('data', chunk => { stdout += chunk })
			child.stderr.on('data', chunk => { stderr += chunk })
		}
		child.on('error', reject)
		child.on('exit', code => {
			if (code === 0) resolve({ stdout, stderr })
			else reject(new Error(`node ${args.join(' ')} exited with ${code}${quiet ? `\n${stdout}\n${stderr}` : ''}`))
		})
	})
}

async function main() {
	const env = readEnvFile(envFile)
	const token = env.DODO_PAYMENTS_API_KEY || process.env.DODO_PAYMENTS_API_KEY
	if (!token) {
		throw new Error(`DODO_PAYMENTS_API_KEY is missing. Run setup-dodo-local.ps1 first, or save it in ${envFile}.`)
	}

	console.log('Dodo bootstrap: using saved test API key')
	console.log('Dodo bootstrap: target environment test mode only')

	if (!env.BETTERPPTX_DODO_TEST_PRODUCT_ID) {
		const productName = `BetterPPTX Premium Test ${new Date().toISOString().slice(0, 10)}`
		const product = await dodo('/products', {
			method: 'POST',
			token,
			body: {
				name: productName,
				description: 'BetterPPTX Premium test product for local activation verification.',
				price: {
					currency: 'USD',
					discount: 0,
					price: 0,
					purchasing_power_parity: false,
					type: 'one_time_price',
				},
				tax_category: 'digital_products',
				license_key_enabled: true,
				license_key_activations_limit: 1,
				license_key_activation_message: 'Paste this key into BetterPPTX when the AI calls betterpptx.auth.activate_key.',
				metadata: {
					product: 'BetterPPTX',
					purpose: 'local-dodo-bootstrap',
				},
			},
		})
		env.BETTERPPTX_DODO_TEST_PRODUCT_ID = product.data?.product_id
		if (!env.BETTERPPTX_DODO_TEST_PRODUCT_ID) throw new Error('Dodo product create succeeded but response did not include product_id.')
		console.log('Dodo bootstrap: created test product', env.BETTERPPTX_DODO_TEST_PRODUCT_ID)
	} else {
		console.log('Dodo bootstrap: using saved test product', env.BETTERPPTX_DODO_TEST_PRODUCT_ID)
	}

	if (!env.BETTERPPTX_DODO_TEST_CUSTOMER_ID) {
		const stamp = new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14)
		const customer = await dodo('/customers', {
			method: 'POST',
			token,
			body: {
				email: `betterpptx-test-${stamp}@example.com`,
				name: 'BetterPPTX Test Customer',
				metadata: {
					product: 'BetterPPTX',
					purpose: 'local-dodo-bootstrap',
				},
			},
		})
		env.BETTERPPTX_DODO_TEST_CUSTOMER_ID = customer.data?.customer_id
		if (!env.BETTERPPTX_DODO_TEST_CUSTOMER_ID) throw new Error('Dodo customer create succeeded but response did not include customer_id.')
		console.log('Dodo bootstrap: created test customer', env.BETTERPPTX_DODO_TEST_CUSTOMER_ID)
	} else {
		console.log('Dodo bootstrap: using saved test customer', env.BETTERPPTX_DODO_TEST_CUSTOMER_ID)
	}

	if (env.BETTERPPTX_VERIFY_ACTIVATION_KEY) {
		const existingValidation = await validateLicensePublic(env.BETTERPPTX_VERIFY_ACTIVATION_KEY)
		if (existingValidation.valid === false) {
			console.log('Dodo bootstrap: saved test license is no longer valid; creating a fresh test license')
			delete env.BETTERPPTX_VERIFY_ACTIVATION_KEY
			delete env.BETTERPPTX_DODO_TEST_LICENSE_ID
		}
	}

	if (!env.BETTERPPTX_VERIFY_ACTIVATION_KEY || !env.BETTERPPTX_DODO_TEST_LICENSE_ID) {
		const licenseKey = env.BETTERPPTX_VERIFY_ACTIVATION_KEY || generateLicenseKey()
		const license = await dodo('/license_keys', {
			method: 'POST',
			token,
			allowConflict: true,
			body: {
				customer_id: env.BETTERPPTX_DODO_TEST_CUSTOMER_ID,
				product_id: env.BETTERPPTX_DODO_TEST_PRODUCT_ID,
				key: licenseKey,
				activations_limit: 1,
				expires_at: null,
			},
		})
		if (license.status === 409) {
			console.log('Dodo bootstrap: license key already exists in Dodo, reusing saved key')
		} else {
			env.BETTERPPTX_DODO_TEST_LICENSE_ID = license.data?.id
			env.BETTERPPTX_VERIFY_ACTIVATION_KEY = license.data?.key || licenseKey
			if (!env.BETTERPPTX_DODO_TEST_LICENSE_ID) throw new Error('Dodo license create succeeded but response did not include id.')
			console.log('Dodo bootstrap: created/imported test license', env.BETTERPPTX_DODO_TEST_LICENSE_ID)
		}
	} else {
		console.log('Dodo bootstrap: using saved test license', env.BETTERPPTX_DODO_TEST_LICENSE_ID)
	}

	const validation = await validateLicensePublic(env.BETTERPPTX_VERIFY_ACTIVATION_KEY)
	if (validation.valid === false) throw new Error('Dodo public validation returned valid:false for the generated test license.')
	console.log('Dodo bootstrap: public license validation accepted the generated test license')

	env.BETTERPPTX_AUTH = 'none'
	env.BETTERPPTX_BILLING_PROVIDER = 'dodo'
	env.BETTERPPTX_DODO_VALIDATE_URL = `${dodoBase}/licenses/validate`
	env.BETTERPPTX_LICENSE_VALIDATION_MODE = 'no-cache'
	env.BETTERPPTX_PUBLIC_MCP_URL = verifyMcpUrl
	env.BETTERPPTX_PORT = String(verifyPort)
	env.BETTERPPTX_HOST = '127.0.0.1'
	env.BETTERPPTX_PRICING_URL ||= 'https://betterpptx.com/pricing'
	env.BETTERPPTX_CHECKOUT_URL ||= env.BETTERPPTX_PRICING_URL
	env.BETTERPPTX_PORTAL_URL ||= env.BETTERPPTX_PRICING_URL
	writeEnvFile(envFile, env)

	const safeStatus = {
		updatedAt: new Date().toISOString(),
		dodoEnvironment: 'test',
		productId: env.BETTERPPTX_DODO_TEST_PRODUCT_ID,
		customerId: env.BETTERPPTX_DODO_TEST_CUSTOMER_ID,
		licenseId: env.BETTERPPTX_DODO_TEST_LICENSE_ID || null,
		validateUrl: env.BETTERPPTX_DODO_VALIDATE_URL,
		localMcpUrl: verifyMcpUrl,
		activationKeySaved: !!env.BETTERPPTX_VERIFY_ACTIVATION_KEY,
	}
	fs.writeFileSync(statusFile, JSON.stringify(safeStatus, null, 2), 'utf8')
	console.log('Dodo bootstrap: saved private env and sanitized status')

	const childEnv = { ...process.env, ...env, BETTERPPTX_PORT: String(verifyPort), BETTERPPTX_PUBLIC_MCP_URL: verifyMcpUrl }
	let server = null
	try {
		server = spawn(process.execPath, ['server-http.mjs'], {
			cwd: here,
			env: childEnv,
			stdio: ['ignore', 'pipe', 'pipe'],
			windowsHide: true,
		})
		server.stdout.on('data', () => {})
		server.stderr.on('data', chunk => {
			const text = String(chunk || '')
			if (/EADDRINUSE|Error|failed/i.test(text)) process.stderr.write(text)
		})
		if (!await waitHttp(`http://127.0.0.1:${verifyPort}/`, 30000)) {
			throw new Error(`Temporary BetterPPTX server did not become ready on port ${verifyPort}.`)
		}
		await runNode(['verify-freemium-gate.mjs', verifyMcpUrl], { env: childEnv })
		console.log('Dodo bootstrap: BetterPPTX Dodo activation verifier passed')
	} finally {
		if (server && !server.killed) server.kill()
	}
}

main().catch(err => {
	console.error('Dodo bootstrap failed:', err?.message || err)
	process.exit(1)
})
