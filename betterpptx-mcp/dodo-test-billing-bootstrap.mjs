function isPaidUsageProduct(product, name, meterId, creditId) {
	if (!product) return false
	if (String(product.name || '').toLowerCase() !== String(name || '').toLowerCase()) return false
	const price = product.price || {}
	if (price.type !== 'usage_based_price') return false
	if (Number(price.fixed_price ?? price.fixedPrice ?? -1) !== 500) return false
	const meters = Array.isArray(price.meters) ? price.meters : []
	return meters.some(meter => {
		const linkedMeterId = meter.meter_id || meter.meterId
		const linkedCreditId = meter.credit_entitlement_id || meter.creditEntitlementId
		return linkedMeterId === meterId && linkedCreditId === creditId && String(meter.meter_units_per_credit ?? meter.meterUnitsPerCredit ?? '') === '1'
	})
}

