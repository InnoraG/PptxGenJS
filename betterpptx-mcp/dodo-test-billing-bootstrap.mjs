async function createCreditEntitlementWithVariants({ token, name }) {
	const errors = []
	for (const variant of creditEntitlementVariants(name)) {
		const response = await dodo('/credit-entitlements', {
			method: 'POST',
			token,
			body: variant.body,
			allowStatuses: [400, 422],
		})
		if (response.status !== 400 && response.status !== 422) return { credit: response.data, variant: variant.name }
		errors.push({ variant: variant.name, error: response.data?.message || response.data?.error || response.data?.raw || String(response.status) })
	}
	const err = new Error('Dodo did not accept any credit entitlement payload variant.')
	err.details = errors.slice(0, 10)
	throw err
}

