param(
	[ValidateSet("Prompt", "Test", "Live")]
	[string]$DodoEnvironment = "Prompt",
	[switch]$SkipOpenDashboard,
	[switch]$NoVerify,
	[switch]$NoStartServer
)

$ErrorActionPreference = "Stop"

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$privateDir = Join-Path $here ".betterpptx-mcp-runtime"
$mcpUrl = "http://127.0.0.1:3344/mcp"

function Read-ExistingEnv($Path) {
	$envMap = @{}
	if (-not (Test-Path -LiteralPath $Path)) { return $envMap }
	foreach ($line in Get-Content -LiteralPath $Path) {
		if ($line -match '^\s*#') { continue }
		if ($line -match '^\s*([^=\s]+)\s*=\s*(.*)\s*$') {
			$name = $Matches[1]
			$value = $Matches[2].Trim()
			if (($value.StartsWith('"') -and $value.EndsWith('"')) -or ($value.StartsWith("'") -and $value.EndsWith("'"))) {
				$value = $value.Substring(1, $value.Length - 2)
			}
			$envMap[$name] = $value -replace '\\n', "`n" -replace '\\"', '"'
		}
	}
	return $envMap
}

function Read-SecretValue($Prompt, $Existing) {
	if ($Existing) {
		$answer = Read-Host "$Prompt is already saved. Press Enter to keep it, or type REPLACE"
		if ($answer -ne "REPLACE") { return $Existing }
	}
	$secure = Read-Host "$Prompt" -AsSecureString
	if ($secure.Length -eq 0) { return "" }
	$ptr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
	try {
		return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($ptr)
	}
	finally {
		[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($ptr)
	}
}

function Read-OptionalValue($Prompt, $Existing, $Default = "") {
	$suffix = ""
	if ($Existing) { $suffix = " [saved: press Enter to keep]" }
	elseif ($Default) { $suffix = " [default: $Default]" }
	$value = Read-Host "$Prompt$suffix"
	if ([string]::IsNullOrWhiteSpace($value)) {
		if ($Existing) { return $Existing }
		return $Default
	}
	return $value.Trim()
}

function Escape-EnvValue($Value) {
	return '"' + (([string]$Value) -replace '\\', '\\' -replace '"', '\"') + '"'
}

function Write-PrivateEnv($Path, $Values, $EnvironmentLabel) {
	New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path) | Out-Null
	$lines = @(
		"# BetterPPTX local Dodo $EnvironmentLabel configuration",
		"# PRIVATE. Do not commit or paste these values in chat.",
		"# Generated by betterpptx-mcp/setup-dodo-local.ps1.",
		""
	)
	foreach ($name in $Values.Keys | Sort-Object) {
		if ([string]::IsNullOrWhiteSpace([string]$Values[$name])) { continue }
		$lines += "$name=$(Escape-EnvValue $Values[$name])"
	}
	Set-Content -LiteralPath $Path -Value $lines -Encoding UTF8
}

function Apply-Env($Values) {
	foreach ($name in $Values.Keys) {
		if ([string]::IsNullOrWhiteSpace([string]$Values[$name])) { continue }
		Set-Item -Path "Env:$name" -Value ([string]$Values[$name])
	}
}

function Wait-Http($Url, $TimeoutSeconds = 20) {
	$deadline = (Get-Date).AddSeconds($TimeoutSeconds)
	while ((Get-Date) -lt $deadline) {
		try {
			Invoke-WebRequest -Uri $Url -UseBasicParsing -TimeoutSec 2 | Out-Null
			return $true
		}
		catch {
			Start-Sleep -Milliseconds 500
		}
	}
	return $false
}

$envChoice = $DodoEnvironment
if ($envChoice -eq "Prompt") {
	Write-Host ""
	Write-Host "Choose Dodo environment" -ForegroundColor Cyan
	Write-Host "Press Enter for TEST mode. Type LIVE only if you are ready to paste the live Dodo API key."
	$choice = Read-Host "Dodo environment"
	if ($choice -match '^(live|l)$') {
		$envChoice = "Live"
	}
	else {
		$envChoice = "Test"
	}
}

$isLive = $envChoice -eq "Live"
$envLabel = if ($isLive) { "live" } else { "test" }
$envLabelUpper = $envLabel.ToUpperInvariant()
$envFileName = if ($isLive) { "dodo-live.env" } else { "dodo-local.env" }
$envFile = Join-Path $privateDir $envFileName
$dodoValidateUrl = if ($isLive) { "https://live.dodopayments.com/licenses/validate" } else { "https://test.dodopayments.com/licenses/validate" }

Write-Host ""
Write-Host "BetterPPTX Dodo $envLabelUpper setup" -ForegroundColor Cyan
Write-Host "This script saves private Dodo values to:"
Write-Host "  $envFile" -ForegroundColor Yellow
Write-Host "That folder is ignored by git. Do not paste these values into chat."
Write-Host ""

if (-not $SkipOpenDashboard) {
	Write-Host "Opening Dodo dashboard and docs..." -ForegroundColor Cyan
	Start-Process "https://app.dodopayments.com/"
	Start-Process "https://docs.dodopayments.com/features/license-keys"
	Start-Process "https://docs.dodopayments.com/features/entitlements/introduction"
	Write-Host ""
	Write-Host "The browser is only for Dodo dashboard steps."
	Write-Host "Come back to this PowerShell window to paste values."
	Write-Host ""
	Read-Host "Press Enter to continue"
}

$existing = Read-ExistingEnv $envFile
$values = @{}

Write-Host ""
Write-Host "Step 1 of 2: Dodo $envLabelUpper API key" -ForegroundColor Cyan
Write-Host "This is the private server API key for Dodo $envLabel mode."
Write-Host "Paste it at the next prompt. The input is hidden while you type or paste."
$values["DODO_PAYMENTS_API_KEY"] = Read-SecretValue "Paste DODO_PAYMENTS_API_KEY ($envLabelUpper mode server API key)" $existing["DODO_PAYMENTS_API_KEY"]

Write-Host ""
Write-Host "Step 2 of 2: Dodo $envLabelUpper customer license key" -ForegroundColor Cyan
Write-Host "This is NOT the Dodo API key." -ForegroundColor Yellow
if ($isLive) {
	Write-Host "It is a real customer/license key generated by Dodo after a live checkout or live purchase."
}
else {
	Write-Host "It is a test customer/license key generated by Dodo after a test checkout or test purchase."
}
Write-Host ""
Write-Host "If you do not have it yet, press Enter at the next question."
Write-Host "The script will save the API key and stop. Then:"
Write-Host "  1. In Dodo $envLabel mode, create a License Key entitlement."
Write-Host "  2. Attach it to your BetterPPTX $envLabel product."
Write-Host "  3. Run a $envLabel checkout/purchase."
Write-Host "  4. Copy the license key Dodo gives the $envLabel customer."
Write-Host "  5. Run this script again and paste that key."
Write-Host ""
$hasActivationKey = Read-Host "Do you already have a Dodo-generated $envLabel customer license key? Type Y for yes, or press Enter for no"
if ($hasActivationKey -match '^(y|yes)$') {
	$values["BETTERPPTX_VERIFY_ACTIVATION_KEY"] = Read-SecretValue "Paste the Dodo-generated $envLabel customer license key" $existing["BETTERPPTX_VERIFY_ACTIVATION_KEY"]
}
else {
	$values["BETTERPPTX_VERIFY_ACTIVATION_KEY"] = $existing["BETTERPPTX_VERIFY_ACTIVATION_KEY"]
	if ($values["BETTERPPTX_VERIFY_ACTIVATION_KEY"]) {
		$keep = Read-Host "A $envLabel customer license key is already saved. Press Enter to keep it, or type CLEAR"
		if ($keep -eq "CLEAR") { $values["BETTERPPTX_VERIFY_ACTIVATION_KEY"] = "" }
	}
}

$values["DODO_PAYMENTS_WEBHOOK_SECRET"] = Read-SecretValue "Optional: paste DODO_PAYMENTS_WEBHOOK_SECRET, or press Enter to skip" $existing["DODO_PAYMENTS_WEBHOOK_SECRET"]
$values["BETTERPPTX_PRICING_URL"] = Read-OptionalValue "Optional: BetterPPTX pricing URL" $existing["BETTERPPTX_PRICING_URL"] "https://betterpptx.com/pricing"
$values["BETTERPPTX_CHECKOUT_URL"] = Read-OptionalValue "Optional: Dodo checkout URL" $existing["BETTERPPTX_CHECKOUT_URL"] $values["BETTERPPTX_PRICING_URL"]
$values["BETTERPPTX_PORTAL_URL"] = Read-OptionalValue "Optional: Dodo customer portal URL" $existing["BETTERPPTX_PORTAL_URL"] $values["BETTERPPTX_PRICING_URL"]
$values["BETTERPPTX_BILLING_PROVIDER"] = "dodo"
$values["BETTERPPTX_DODO_ENVIRONMENT"] = $envLabel
$values["BETTERPPTX_LICENSE_VALIDATION_MODE"] = "no-cache"
$values["BETTERPPTX_DODO_VALIDATE_URL"] = $dodoValidateUrl
$values["BETTERPPTX_AUTH"] = "none"
$values["BETTERPPTX_HOST"] = "127.0.0.1"
$values["BETTERPPTX_PORT"] = "3344"
$values["BETTERPPTX_PUBLIC_MCP_URL"] = $mcpUrl

Write-PrivateEnv $envFile $values $envLabel
Apply-Env $values

Write-Host ""
Write-Host "Saved private local Dodo $envLabel env file." -ForegroundColor Green

if ([string]::IsNullOrWhiteSpace([string]$values["BETTERPPTX_VERIFY_ACTIVATION_KEY"])) {
	Write-Host ""
	Write-Host "No Dodo-generated $envLabel license key was provided." -ForegroundColor Yellow
	Write-Host "I saved the API-key setup, but Dodo activation cannot be tested yet."
	Write-Host "Generate a $envLabel customer/license key in Dodo, rerun this script, and paste it at the activation-key prompt."
	if ($isLive -and -not $NoVerify -and (Get-Command node -ErrorAction SilentlyContinue)) {
		Write-Host ""
		Write-Host "Running read-only live Dodo API-key verifier..." -ForegroundColor Cyan
		Push-Location $here
		try {
			node .\dodo-live-verify.mjs
			if ($LASTEXITCODE -ne 0) { throw "Live Dodo verifier failed with exit code $LASTEXITCODE." }
		}
		finally {
			Pop-Location
		}
	}
	exit 0
}

if ($NoVerify) {
	Write-Host "Verification skipped because -NoVerify was provided."
	exit 0
}

if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
	Write-Host "Node.js was not found on PATH, so I cannot run the verifier from this script." -ForegroundColor Yellow
	Write-Host "The env file is ready at: $envFile"
	exit 0
}

$serverStarted = $false
$serverProcess = $null

if (-not (Wait-Http "http://127.0.0.1:3344/" 2)) {
	if ($NoStartServer) {
		Write-Host "No local BetterPPTX server is reachable, and -NoStartServer was provided." -ForegroundColor Yellow
		Write-Host "Start it separately, then run:"
		Write-Host "  node verify-freemium-gate.mjs $mcpUrl"
		exit 0
	}
	Write-Host "Starting local BetterPPTX MCP server on $mcpUrl ..." -ForegroundColor Cyan
	$serverProcess = Start-Process -FilePath "node" -ArgumentList ".\server-http.mjs" -WorkingDirectory $here -PassThru -WindowStyle Hidden
	$serverStarted = $true
	if (-not (Wait-Http "http://127.0.0.1:3344/" 25)) {
		if ($serverProcess -and -not $serverProcess.HasExited) { Stop-Process -Id $serverProcess.Id -Force }
		throw "Local BetterPPTX server did not become ready on http://127.0.0.1:3344/"
	}
}
else {
	Write-Host "Using already-running local BetterPPTX server on $mcpUrl." -ForegroundColor Cyan
}

try {
	Write-Host "Running Dodo activation verifier..." -ForegroundColor Cyan
	Push-Location $here
	try {
		node .\verify-freemium-gate.mjs $mcpUrl
		if ($LASTEXITCODE -ne 0) { throw "Verifier failed with exit code $LASTEXITCODE." }
	}
	finally {
		Pop-Location
	}
	Write-Host ""
	Write-Host "Dodo activation verifier passed." -ForegroundColor Green
}
finally {
	if ($serverStarted -and $serverProcess -and -not $serverProcess.HasExited) {
		Stop-Process -Id $serverProcess.Id -Force
		Write-Host "Stopped the temporary local BetterPPTX server."
	}
}
