import fs from 'node:fs';
import path from 'node:path';

// Build-time embedder: reads raw XML templates and generates a TS module with embedded strings.
// This supports single-file browser builds (no runtime filesystem access).

const ROOT = process.cwd();
const TEMPLATE_DIR = path.join(ROOT, 'src', 'ui-truth-templates');
const OUT_TS = path.join(ROOT, 'src', 'ui-truth-templates.embedded.ts');

const files = fs.readdirSync(TEMPLATE_DIR)
  .filter(f => f.endsWith('.xml'))
  .sort();

const templates = {};
for (const f of files) {
  const key = path.basename(f, '.xml');
  const xml = fs.readFileSync(path.join(TEMPLATE_DIR, f), 'utf8');
  templates[key] = xml;
}

const header = `/**\n * AUTO-GENERATED FILE.\n * Generated by tools/embed-ui-truth-templates.mjs\n *\n * Contains embedded UI-truth OOXML timing templates as strings, for single-file bundling.\n */\n\n`;

const body = `export const UI_TRUTH_TEMPLATES: Record<string, string> = ${JSON.stringify(templates, null, 2)} as const;\n`;

fs.writeFileSync(OUT_TS, header + body, 'utf8');
console.log(`Wrote ${OUT_TS} with ${files.length} templates`);
