import * as fs from 'node:fs'
import * as path from 'node:path'

const __dirname = path.dirname(new URL(import.meta.url).pathname)
const here = process.platform === 'win32' && __dirname.startsWith('/') ? __dirname.slice(1) : __dirname
const privateDir = path.join(here, '.claudepptxmcp-runtime')
const envFile = path.join(privateDir, 'dodo-live.env')
const statusFile = path.join(privateDir, 'dodo-live-product-status.json')
const dodoBase = 'https://live.dodopayments.com'

function readEnvFile(file) {
	if (!fs.existsSync(file)) return {}
	const env = {}
	for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
		const m = line.match(/^\s*([^#=\s]+)\s*=\s*(.*?)\s*$/)
		if (!m) continue
		let value = m[2].trim()
		if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1)
		env[m[1]] = value.replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\')
	}
	return env
}

function escapeEnvValue(value) {
	return `"${String(value ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function writeEnvFile(file, values) {
	fs.mkdirSync(path.dirname(file), { recursive: true })
	const lines = [
		'# BetterPPTX local Dodo live configuration',
		'# PRIVATE. Do not commit or paste these values in chat.',
		'# Generated by claudepptxmcp/setup-dodo-local.ps1 and Dodo live bootstrap tools.',
		'',
	]
	for (const key of Object.keys(values).sort()) {
		const value = values[key]
		if (value === undefined || value === null || String(value).trim() === '') continue
		lines.push(`${key}=${escapeEnvValue(value)}`)
	}
	fs.writeFileSync(file, `${lines.join('\n')}\n`, { encoding: 'utf8', mode: 0o600 })
}

function argValue(name) {
	const prefix = `--${name}=`
	const item = process.argv.find(a => a.startsWith(prefix))
	return item ? item.slice(prefix.length) : ''
}

function hasArg(name) {
	return process.argv.includes(`--${name}`)
}

function extractItems(data) {
	if (Array.isArray(data)) return data
	for (const key of ['items', 'data', 'results', 'products']) {
		if (Array.isArray(data?.[key])) return data[key]
	}
	return []
}

async function dodo(pathname, { method = 'GET', body, token } = {}) {
	const headers = { Accept: 'application/json' }
	if (token) headers.Authorization = `Bearer ${token}`
	if (body !== undefined) headers['Content-Type'] = 'application/json'
	const response = await fetch(`${dodoBase}${pathname}`, {
		method,
		headers,
		body: body === undefined ? undefined : JSON.stringify(body),
	})
	const raw = await response.text()
	let data = null
	try { data = raw ? JSON.parse(raw) : null } catch { data = { raw } }
	if (!response.ok) {
		const msg = data?.message || data?.error || data?.raw || response.statusText
		throw new Error(`Dodo live ${method} ${pathname} failed with HTTP ${response.status}: ${msg}`)
	}
	return data
}

function summarizeProduct(product = {}) {
	return {
		productId: product.product_id || product.id || null,
		name: product.name || null,
		isRecurring: product.is_recurring ?? null,
		licenseKeyEnabled: product.license_key_enabled ?? null,
		taxCategory: product.tax_category || null,
		metadataProduct: product.metadata?.product || null,
	}
}

function livePriceCents(env) {
	const raw = argValue('price-cents') || env.BETTERPPTX_DODO_LIVE_PRODUCT_PRICE_CENTS
	return Math.max(0, Number.parseInt(String(raw || ''), 10) || 0)
}

function liveProductName(env) {
	return argValue('name') || env.BETTERPPTX_DODO_LIVE_PRODUCT_NAME || 'BetterPPTX Premium'
}

function writeStatus(status) {
	fs.mkdirSync(privateDir, { recursive: true })
	fs.writeFileSync(statusFile, `${JSON.stringify({ updatedAt: new Date().toISOString(), ...status }, null, 2)}\n`, 'utf8')
}

async function main() {
	const env = readEnvFile(envFile)
	const token = env.DODO_PAYMENTS_API_KEY || process.env.DODO_PAYMENTS_API_KEY
	if (!token) throw new Error(`DODO_PAYMENTS_API_KEY is missing from ${envFile}.`)

	const explicitProductId = argValue('product-id') || env.BETTERPPTX_DODO_LIVE_PRODUCT_ID
	if (explicitProductId) {
		const product = await dodo(`/products/${encodeURIComponent(explicitProductId)}`, { token })
		env.BETTERPPTX_DODO_LIVE_PRODUCT_ID = product.product_id || product.id || explicitProductId
		env.BETTERPPTX_DODO_LIVE_PRODUCT_NAME = product.name || env.BETTERPPTX_DODO_LIVE_PRODUCT_NAME || 'BetterPPTX Premium'
		writeEnvFile(envFile, env)
		writeStatus({ dodoEnvironment: 'live', product: summarizeProduct(product), needsProduct: false, created: false })
		console.log(`DODO LIVE PRODUCT: PASS using saved product ${env.BETTERPPTX_DODO_LIVE_PRODUCT_ID}`)
		return
	}

	const products = extractItems(await dodo('/products', { token }))
	const candidates = products.filter(p => /betterpptx/i.test(String(p?.name || '')) || /betterpptx/i.test(String(p?.metadata?.product || '')))
	if (candidates.length === 1) {
		const product = candidates[0]
		env.BETTERPPTX_DODO_LIVE_PRODUCT_ID = product.product_id || product.id
		env.BETTERPPTX_DODO_LIVE_PRODUCT_NAME = product.name || 'BetterPPTX Premium'
		writeEnvFile(envFile, env)
		writeStatus({ dodoEnvironment: 'live', product: summarizeProduct(product), needsProduct: false, created: false })
		console.log(`DODO LIVE PRODUCT: PASS discovered product ${env.BETTERPPTX_DODO_LIVE_PRODUCT_ID}`)
		return
	}
	if (candidates.length > 1) {
		writeStatus({ dodoEnvironment: 'live', candidates: candidates.map(summarizeProduct), needsProduct: false, needsProductSelection: true })
		throw new Error('Multiple BetterPPTX-like live products exist. Set BETTERPPTX_DODO_LIVE_PRODUCT_ID in dodo-live.env, then rerun.')
	}

	if (!hasArg('create')) {
		writeStatus({ dodoEnvironment: 'live', productCount: products.length, needsProduct: true, createRequired: true })
		console.log('DODO LIVE PRODUCT: NEEDS_PRODUCT no BetterPPTX live product exists yet')
		console.log('To create one, set BETTERPPTX_DODO_LIVE_PRODUCT_PRICE_CENTS in dodo-live.env and rerun with --create.')
		process.exitCode = 2
		return
	}

	const priceCents = livePriceCents(env)
	if (!Number.isInteger(priceCents) || priceCents <= 0) {
		writeStatus({ dodoEnvironment: 'live', needsProduct: true, needsPrice: true })
		throw new Error('Refusing to create a live Dodo product without an explicit positive BETTERPPTX_DODO_LIVE_PRODUCT_PRICE_CENTS value.')
	}

	const name = liveProductName(env)
	const product = await dodo('/products', {
		method: 'POST',
		token,
		body: {
			name,
			description: env.BETTERPPTX_DODO_LIVE_PRODUCT_DESCRIPTION || 'BetterPPTX premium activation for full-deck native PowerPoint generation and editing.',
			price: {
				currency: env.BETTERPPTX_DODO_LIVE_PRODUCT_CURRENCY || 'USD',
				discount: 0,
				price: priceCents,
				purchasing_power_parity: true,
				type: 'one_time_price',
			},
			tax_category: env.BETTERPPTX_DODO_LIVE_TAX_CATEGORY || 'digital_products',
			license_key_enabled: true,
			license_key_activations_limit: Math.max(1, Number.parseInt(env.BETTERPPTX_DODO_LIVE_LICENSE_ACTIVATIONS_LIMIT || '3', 10) || 3),
			license_key_activation_message: 'Use this BetterPPTX activation key when your AI client asks for premium activation. Do not paste it into public chats.',
			metadata: {
				product: 'BetterPPTX',
				purpose: 'production-premium-activation',
			},
		},
	})

	env.BETTERPPTX_DODO_LIVE_PRODUCT_ID = product.product_id || product.id
	env.BETTERPPTX_DODO_LIVE_PRODUCT_NAME = product.name || name
	env.BETTERPPTX_DODO_LIVE_PRODUCT_PRICE_CENTS = String(priceCents)
	env.BETTERPPTX_CHECKOUT_URL ||= env.BETTERPPTX_PRICING_URL || 'https://betterpptx.com/pricing'
	env.BETTERPPTX_PORTAL_URL ||= env.BETTERPPTX_PRICING_URL || 'https://betterpptx.com/pricing'
	writeEnvFile(envFile, env)
	writeStatus({ dodoEnvironment: 'live', product: summarizeProduct(product), needsProduct: false, created: true })
	console.log(`DODO LIVE PRODUCT: PASS created product ${env.BETTERPPTX_DODO_LIVE_PRODUCT_ID}`)
}

main().catch(err => {
	console.error(`DODO LIVE PRODUCT: FAIL - ${err?.message || err}`)
	process.exitCode = 1
})
