async function createCreditEntitlementWithVariants({ token, name }) {
	const errors = []
	for (const variant of creditEntitlementVariants(name)) {
		const response = await dodo('/credit-entitlements', {
			method: 'POST',
			token,
			body: variant.body,
			allowStatuses: [400, 422],
		})
		if (response.status !== 400 && response.status !== 422) return { credit: response.data, variant: variant.name }
		errors.push({ variant: variant.name, error: response.data?.message || response.data?.error || response.data?.raw || String(response.status) })
	}
	const err = new Error('Dodo did not accept any credit entitlement payload variant.')
	err.details = errors.slice(0, 10)
	throw err
}

async function createProductWithVariants({ token, name, description, priceVariants, creditId, creditsAmount, metadata }) {
	const mappingVariants = creditMappings(creditId, creditsAmount)
	const errors = []
	for (const priceVariant of priceVariants) {
		for (let i = 0; i < mappingVariants.length; i++) {
			const body = {
				name,
				description,
				price: priceVariant.price,
				tax_category: 'digital_products',
				license_key_enabled: true,
				license_key_activations_limit: 3,
				license_key_activation_message: 'Use this BetterPPTX test activation key when your AI client asks for premium activation.',
				credit_entitlements: [mappingVariants[i]],
				metadata,
			}
			const response = await dodo('/products', { method: 'POST', token, body, allowStatuses: [400, 422] })
			if (response.status !== 400 && response.status !== 422) return { product: response.data, variant: `${priceVariant.name}/creditMapping${i + 1}` }
			errors.push({ variant: `${priceVariant.name}/creditMapping${i + 1}`, error: response.data?.message || response.data?.error || response.data?.raw || '422' })
		}
	}
	const err = new Error(`Dodo did not accept any product payload variant for ${name}.`)
	err.details = errors.slice(0, 10)
	throw err
}

async function main() {
	const env = readEnvFile(envFile)
	const token = env.DODO_PAYMENTS_API_KEY || process.env.DODO_PAYMENTS_API_KEY
	if (!token) throw new Error(`DODO_PAYMENTS_API_KEY is missing from ${envFile}.`)

	const notes = []
	const creditName = 'BetterPPTX Generation Credits Test'
	const products = extractItems((await dodo('/products', { token })).data)
	let credit = null
	let acceptedCreditVariant = env.BETTERPPTX_DODO_TEST_CREDIT_VARIANT || null
	if (env.BETTERPPTX_DODO_TEST_CREDIT_ENTITLEMENT_ID) {
		credit = (await dodo(`/credit-entitlements/${encodeURIComponent(env.BETTERPPTX_DODO_TEST_CREDIT_ENTITLEMENT_ID)}`, { token })).data
	} else {
		const credits = extractItems((await dodo('/credit-entitlements', { token })).data)
		credit = byName(credits, creditName)
		if (!credit) {
			const created = await createCreditEntitlementWithVariants({ token, name: creditName })
			credit = created.credit
			acceptedCreditVariant = created.variant
			notes.push('created credit entitlement')
		}
		env.BETTERPPTX_DODO_TEST_CREDIT_ENTITLEMENT_ID = credit.id
	}
	if (acceptedCreditVariant) env.BETTERPPTX_DODO_TEST_CREDIT_VARIANT = acceptedCreditVariant

	let subscriptionProduct = env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_PRODUCT_ID
		? (await dodo(`/products/${encodeURIComponent(env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_PRODUCT_ID)}`, { token })).data
		: byName(products, 'BetterPPTX Starter Test - $5/mo')
	let acceptedSubscriptionVariant = env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_VARIANT || null
	if (!subscriptionProduct) {
		const created = await createProductWithVariants({
			token,
			name: 'BetterPPTX Starter Test - $5/mo',
			description: 'Test subscription: $5/month converted into BetterPPTX credits, with license-key activation.',
			priceVariants: subscriptionPriceVariants(),
			creditId: credit.id,
			creditsAmount: 500,
			metadata: { product: 'BetterPPTX', purpose: 'test-subscription-credit-plan' },
		})
		subscriptionProduct = created.product
		acceptedSubscriptionVariant = created.variant
		notes.push('created subscription product')
	}
	env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_PRODUCT_ID = subscriptionProduct.product_id || subscriptionProduct.id
	if (acceptedSubscriptionVariant) env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_VARIANT = acceptedSubscriptionVariant

	let topUpProduct = env.BETTERPPTX_DODO_TEST_TOPUP_PRODUCT_ID
		? (await dodo(`/products/${encodeURIComponent(env.BETTERPPTX_DODO_TEST_TOPUP_PRODUCT_ID)}`, { token })).data
		: byName(products, 'BetterPPTX Credits Top-Up Test - $5')
	let acceptedTopUpVariant = env.BETTERPPTX_DODO_TEST_TOPUP_VARIANT || null
	if (!topUpProduct) {
		const created = await createProductWithVariants({
			token,
			name: 'BetterPPTX Credits Top-Up Test - $5',
			description: 'Test one-time top-up: $5 of BetterPPTX credits.',
			priceVariants: [{
				name: 'one_time_price',
				price: {
					currency: 'USD',
					discount: 0,
					price: 500,
					purchasing_power_parity: true,
					type: 'one_time_price',
				},
			}],
			creditId: credit.id,
			creditsAmount: 500,
			metadata: { product: 'BetterPPTX', purpose: 'test-credit-topup' },
		})
		topUpProduct = created.product
		acceptedTopUpVariant = created.variant
		notes.push('created top-up product')
	}
	env.BETTERPPTX_DODO_TEST_TOPUP_PRODUCT_ID = topUpProduct.product_id || topUpProduct.id
	if (acceptedTopUpVariant) env.BETTERPPTX_DODO_TEST_TOPUP_VARIANT = acceptedTopUpVariant

	let checkoutSession = null
	try {
		checkoutSession = (await dodo('/checkouts', {
			method: 'POST',
			token,
			body: {
				product_cart: [{ product_id: env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_PRODUCT_ID, quantity: 1 }],
				customer: {
					email: `betterpptx-sub-test-${Date.now()}@example.com`,
					name: 'BetterPPTX Subscription Test Customer',
				},
				subscription_data: { trial_period_days: 0 },
				return_url: 'https://betterpptx.com/checkout/test-success',
				metadata: { product: 'BetterPPTX', purpose: 'test-subscription-checkout' },
			},
		})).data
		env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_CHECKOUT_URL = checkoutSession.checkout_url || env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_CHECKOUT_URL
		notes.push('created subscription checkout session')
	} catch (err) {
		notes.push(`checkout session skipped: ${err?.message || err}`)
	}

	env.BETTERPPTX_DODO_TEST_CREDIT_AMOUNT = '500'
	env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_PRICE_CENTS = '500'
	env.BETTERPPTX_DODO_TEST_TOPUP_PRICE_CENTS = '500'
	writeEnvFile(envFile, env)
	const status = publicStatus({ creditEntitlement: credit, subscriptionProduct, topUpProduct, checkoutSession, acceptedCreditVariant, acceptedSubscriptionVariant, acceptedTopUpVariant, notes })
	fs.mkdirSync(privateDir, { recursive: true })
	fs.writeFileSync(statusFile, `${JSON.stringify(status, null, 2)}\n`, 'utf8')
	console.log(`DODO TEST BILLING: PASS credit=${credit.id} subscription=${env.BETTERPPTX_DODO_TEST_SUBSCRIPTION_PRODUCT_ID} topup=${env.BETTERPPTX_DODO_TEST_TOPUP_PRODUCT_ID} checkout=${checkoutSession?.checkout_url ? 'yes' : 'no'}`)
}

main().catch(err => {
	console.error(`DODO TEST BILLING: FAIL - ${err?.message || err}`)
	if (err?.details) console.error(JSON.stringify(err.details, null, 2))
	process.exit(1)
})
